"""
handlers/help_registry.py — Single-Source-of-Truth Command & Help Catalog.

Maintains structured metadata for every slash command, nested subcommand,
Discord context menu, and reaction trigger across all Cogs, together with
workflow playbooks, bilingual/i18n lookup helpers, search, pagination, and
automated CommandTree parity auditing.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterable, Optional

from discord import app_commands

from locales.i18n import t


@dataclass(frozen=True)
class HelpCategoryMeta:
    """Metadata for a /help navigation category."""

    key: str
    emoji: str
    label_key: str
    desc_key: str
    fallback_label_en: str
    fallback_label_th: str
    fallback_desc_en: str
    fallback_desc_th: str
    is_legacy: bool = False

    def label(self, lang: str) -> str:
        val = t(self.label_key, lang)
        if val == self.label_key:
            return self.fallback_label_th if lang == "th" else self.fallback_label_en
        return val

    def description(self, lang: str) -> str:
        val = t(self.desc_key, lang)
        if val == self.desc_key:
            return self.fallback_desc_th if lang == "th" else self.fallback_desc_en
        return val


@dataclass(frozen=True)
class HelpCommandMeta:
    """Structured metadata for one leaf slash command, context menu, or trigger."""

    path: str
    category: str
    emoji: str
    desc_en: str
    desc_th: str
    params: tuple[str, ...] = ()
    example: str = ""
    scope: str = "personal"  # personal | server | project | admin | owner
    keywords: str = ""
    related: tuple[str, ...] = ()
    subgroup: str = ""
    kind: str = "slash"  # slash | context | trigger
    in_command_tree: bool = True

    @property
    def display_command(self) -> str:
        if self.kind == "slash":
            return f"/{self.path}"
        if self.kind == "context":
            return f"Context Menu: {self.path}"
        return self.path

    @property
    def is_admin(self) -> bool:
        return self.scope in ("admin", "owner")

    def description(self, lang: str) -> str:
        return self.desc_th if lang == "th" else self.desc_en

    def syntax(self) -> str:
        if self.kind != "slash":
            return self.display_command
        if not self.params:
            return f"/{self.path}"
        arg_text = " ".join(f"[{p}]" for p in self.params)
        return f"/{self.path} {arg_text}"


@dataclass(frozen=True)
class HelpWorkflowMeta:
    """Role-based Quick Start workflow playbook shown in /help."""

    key: str
    emoji: str
    title_en: str
    title_th: str
    audience_en: str
    audience_th: str
    steps_en: tuple[str, ...]
    steps_th: tuple[str, ...]

    def title(self, lang: str) -> str:
        return self.title_th if lang == "th" else self.title_en

    def audience(self, lang: str) -> str:
        return self.audience_th if lang == "th" else self.audience_en

    def steps(self, lang: str) -> tuple[str, ...]:
        return self.steps_th if lang == "th" else self.steps_en


