COMMAND_MAP: dict[str, HelpCommandMeta] = {c.path.lower(): c for c in HELP_COMMANDS}


def get_category_meta(category_key: str) -> HelpCategoryMeta:
    """Return HelpCategoryMeta for `category_key`, falling back to `overview`."""
    return CATEGORY_MAP.get(category_key, CATEGORY_MAP["overview"])


def get_command_meta(query_or_path: str) -> Optional[HelpCommandMeta]:
    """Resolve exact command metadata by normalized path (leading `/` optional)."""
    cleaned = query_or_path.strip().lstrip("/").lower()
    return COMMAND_MAP.get(cleaned)


def get_commands_for_category(
    category_key: str,
    *,
    include_admin: bool = True,
) -> list[HelpCommandMeta]:
    """Return ordered commands inside a category, optionally filtering admin commands."""
    return [
        cmd
        for cmd in HELP_COMMANDS
        if cmd.category == category_key and (include_admin or not cmd.is_admin)
    ]


def count_commands_for_category(
    category_key: str,
    *,
    include_admin: bool = True,
) -> int:
    if category_key == "overview":
        return len(HELP_COMMANDS) if include_admin else sum(1 for c in HELP_COMMANDS if not c.is_admin)
    if category_key == "tips":
        return len(HELP_WORKFLOWS) + 5
    return len(get_commands_for_category(category_key, include_admin=include_admin))


def paginate_commands(
    commands_list: list[HelpCommandMeta],
    page: int = 1,
    page_size: int = 7,
) -> tuple[list[HelpCommandMeta], int, int]:
    """Slice commands into a 1-indexed page, returning `(items, clamped_page, total_pages)`."""
    if not commands_list:
        return [], 1, 1
    total_pages = max(1, (len(commands_list) + page_size - 1) // page_size)
    clamped = max(1, min(page, total_pages))
    start = (clamped - 1) * page_size
    return commands_list[start : start + page_size], clamped, total_pages


def search_help_commands(
    query: str,
    lang: str = "en",
    *,
    include_admin: bool = True,
    limit: int = 25,
) -> list[HelpCommandMeta]:
    """Score and return matching commands across path, EN/TH description, subgroup, and keywords."""
    q = query.strip().lstrip("/").lower()
    if not q:
        pool = [c for c in HELP_COMMANDS if include_admin or not c.is_admin]
        return pool[:limit]

    tokens = [tok for tok in q.split() if tok]
    scored: list[tuple[int, int, HelpCommandMeta]] = []
    for idx, cmd in enumerate(HELP_COMMANDS):
        if not include_admin and cmd.is_admin:
            continue
        path_l = cmd.path.lower()
        haystack = " ".join(
            (
                path_l,
                cmd.desc_en.lower(),
                cmd.desc_th.lower(),
                cmd.keywords.lower(),
                cmd.subgroup.lower(),
                " ".join(cmd.params).lower(),
            )
        )
        if not all(tok in haystack for tok in tokens):
            continue

        if path_l == q:
            rank = 0
        elif path_l.startswith(q):
            rank = 1
        elif q in path_l:
            rank = 2
        elif q in cmd.keywords.lower():
            rank = 3
        else:
            rank = 4
        scored.append((rank, idx, cmd))

    scored.sort(key=lambda item: (item[0], item[1]))
    return [item[2] for item in scored[:limit]]


def _walk_group_leaves(group: app_commands.Group) -> Iterable[str]:
    for child in group.commands:
        if isinstance(child, app_commands.Group):
            yield from _walk_group_leaves(child)
        else:
            yield child.qualified_name


def extract_tree_leaf_paths(tree: app_commands.CommandTree) -> set[str]:
    """Return every leaf slash command path and context menu name in `tree`."""
    paths: set[str] = set()
    for item in tree.get_commands():
        if isinstance(item, app_commands.Group):
            paths.update(_walk_group_leaves(item))
        else:
            paths.add(item.qualified_name)
    return paths


def audit_tree_coverage(tree: app_commands.CommandTree) -> tuple[set[str], set[str]]:
    """
    Compare live Discord `CommandTree` against `HELP_COMMANDS`.

    Returns `(missing_from_help, stale_in_help)`. Both sets are empty when
    `/help` has 100% 1:1 parity with every live registered command/context menu.
    """
    live_paths = extract_tree_leaf_paths(tree)
    documented_paths = {cmd.path for cmd in HELP_COMMANDS if cmd.in_command_tree}
    missing = live_paths - documented_paths
    stale = documented_paths - live_paths
    return missing, stale

